export default function Sidebar() {
    const pathname = usePathname();
    const { user, signOut } = useAuth();

    // Determine role from URL prefix
    const isDoctor = pathname.startsWith("/doctor");
    const navItems = isDoctor ? doctorNav : patientNav;
    const homeHref = isDoctor ? "/doctor/dashboard" : "/patient/dashboard";
    const roleLabel = isDoctor ? "Doctor" : "Patient";

    const displayName = user?.user_metadata?.full_name || user?.email?.split("@")[0] || roleLabel;
    const initials = displayName.substring(0, 2).toUpperCase();

    return (
        <aside className="sidebar">
            {/* Header / Logo */}
            <div className="sidebar-header">
                <a href={homeHref} className="sidebar-logo">
                    <div className="sidebar-logo-icon">
                        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                            <path d="M22 12h-4l-3 9L9 3l-3 9H2" />
                        </svg>
                    </div>
                    <div className="sidebar-logo-text">
                        <h2>Mediq</h2>
                        <span>Smart EMR</span>
                    </div>
                </a>
            </div>

            {/* Navigation */}
            <nav className="sidebar-nav">
                <div className="sidebar-section-title">{roleLabel} Portal</div>
                {navItems.map((item) => (
                    <a
                        key={item.href}
                        href={item.href}
                        className={`sidebar-link ${pathname === item.href ? "active" : ""}`}
                    >
                        {item.icon}
                        <span>{item.label}</span>
                    </a>
                ))}
            </nav>

            {/* User + Logout */}
            <div className="sidebar-footer">
                <div className="sidebar-user">
                    <div className="sidebar-avatar">{initials}</div>
                    <div className="sidebar-user-info">
                        <div className="name">{displayName}</div>
                        <div className="role">{roleLabel}</div>
                    </div>
                </div>
                <button className="logout-btn" onClick={signOut} aria-label="Sign out">
                    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                        <path d="M9 21H5a2 2 0 01-2-2V5a2 2 0 012-2h4" />
                        <polyline points="16 17 21 12 16 7" />
                        <line x1="21" y1="12" x2="9" y2="12" />
                    </svg>
                    <span>Sign Out</span>
                </button>
            </div>
        </aside>
    );
}
